#!/usr/bin/env python3
"""Generate standalone shareable pages (people/books/map) from sections in index.html.
Run after editing those sections: python3 tools/build-pages.py"""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
idx = (root/'index.html').read_text()
head = idx[:idx.index('</head>')]
header = idx[idx.index('<header class="topbar">'):idx.index('</header>')+9]
scripts = re.findall(r'<script src="\./(?:data|map-data|app|museum)\.js[^"]*" defer></script>', idx)
def section(i):
    m = re.search(r'<section[^>]*id="%s"[^>]*>.*?\n</section>' % i, idx, re.S)
    return m.group(0)
PAGES = {
 'people': ('Reformers & Puritans', 'Portraits and short biographies of the forerunners, Reformers, Puritans and Great Awakening preachers.', ['people'], 'assets/hero-wittenberg.jpg'),
 'books':  ('The Reformed bookshelf', 'Theology, commentaries, Puritan classics, devotional works and biographies, with where to start.', ['shelf'], 'assets/hero-wittenberg.jpg'),
 'map':    ('Timeline & map', 'Where the Reformation and the Puritan story happened, from Wittenberg to New England, with an interactive timeline.', ['era','map'], 'assets/hero-wittenberg.jpg'),
}
links = '<a href="./people.html">People</a><a href="./books.html">Books</a><a href="./map.html">Map</a>'
for slug,(title,desc,ids,img) in PAGES.items():
    url = 'https://reformedatlas.com/%s.html' % slug
    h = re.sub(r'<title>.*?</title>', '<title>%s — Reformed Atlas</title>' % title.replace('&','&amp;'), head)
    for k,v in [('description',desc)]:
        h = re.sub(r'<meta name="description" content="[^"]*">', '<meta name="description" content="%s">' % desc, h)
    h = re.sub(r'(property="og:title" content=")[^"]*', r'\g<1>%s — Reformed Atlas' % title.replace('&','&amp;'), h)
    h = re.sub(r'(name="twitter:title" content=")[^"]*', r'\g<1>%s — Reformed Atlas' % title.replace('&','&amp;'), h)
    h = re.sub(r'(property="og:description" content=")[^"]*', r'\g<1>'+desc, h)
    h = re.sub(r'(name="twitter:description" content=")[^"]*', r'\g<1>'+desc, h)
    h = re.sub(r'(property="og:url" content=")[^"]*', r'\g<1>'+url, h)
    h += '<link rel="canonical" href="%s">\n' % url
    hd = header.replace('href="#top"', 'href="./"')
    hd = re.sub(r'href="#([\w-]+)"', r'href="./#\1"', hd)
    hd = hd.replace('</nav>', '  <span class="nav-pages">'+links+'</span>\n  </nav>')
    body = '\n\n'.join(section(i) for i in ids)
    back = ' · '.join('<a href="./#%s">See it in the full atlas</a>' % ids[-1:] [0] for _ in [0])
    out = (h + '</head>\n<body class="subpage">\n<a class="skip" href="#main">Skip to content</a>\n' + hd +
      '\n\n<main id="main">\n' + body + '\n</main>\n\n<footer class="foot">\n  <div class="wrap"><p><b>Reformed Atlas</b> · Soli Deo Gloria</p><p class="small"><a href="./">← Back to the full atlas</a> · ' + back +
      ' · Pages: ' + links.replace('</a><a','</a> · <a') + '</p><p class="small">Facts are linked to public sources throughout. Image credits: <a href="https://github.com/mjbanakSATCOM/sola-atlas/blob/main/assets/CREDITS.md" target="_blank" rel="noopener">CREDITS</a>.</p></div>\n</footer>\n' +
      '\n'.join(scripts) + '\n<!-- generated by tools/build-pages.py from index.html; edit index.html then rerun -->\n</body>\n</html>\n')
    (root/('%s.html'%slug)).write_text(out)
    print('wrote', slug)
